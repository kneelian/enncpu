; exceptions load an addr from
; this table by offset; XS contains
; the offset to the correct handler
; and the interrupt routine uses
; this offset to find where to jump
@EX_TABLE
.INT16 @KILL            ; 0x00
.INT16 @EX_TIMER_EVENT  ; 0x02
.INT16 @EX_KBD_EVENT    ; 0x04
.INT16 @KILL            ; 0x06

@EX_TIMER
.INT24 0x00
.INT24 0x00
@EX_TIMER_EVENT
	ADRL  A, @EX_TIMER
	ADRM  A, @EX_TIMER
	LDRS  B, A
	ADD   B, #1
	STRS  B, A+
	CEQ   B, #0
	LDRS  B, A
	ADD.P B, #1
	STRS  B, A
	RET

@EX_KBD_EVENT
	ADRL  B, @KBD_MAILBOX
	ADRM  B, @KBD_MAILBOX
	ADRH  B, @KBD_MAILBOX

	LDRW  A, B

	MOV   B, KEY_Q

	CEQ   A, B
	JMO.P @KILL

	GETL  A, A

	JLA   @PUTCHAR_CURSOR

	MOV  A, #0 ; clearing exception state
	WXS  A
	RET
@KILL
	JLA @GET_TIMER
	ERR
@EXVEC
	MASK
	PSHS A
	PSHS B
	RPS  A
	PSHS A

	RXS  A
	ADRL B, @EX_TABLE
